const defaultPassword = (email) => email.split('@')[0] + '123';

function hashPassword(password) {
  const salt = crypto.randomBytes(16).toString('hex');
  const hash = crypto.createHash('sha256').update(`${salt}:${password}`, 'utf8').digest('hex');
  return `${salt}$${hash}`;
}

const txt = (v) => ({ type: 'text', value: v == null ? null : String(v) });
const intOrNull = (v) => (v == null ? { type: 'null' } : { type: 'integer', value: String(v) });

async function turso(stmts) {
  const requests = stmts.map((s) => ({ type: 'execute', stmt: { sql: s.sql, args: s.args, want_rows: false } }));
  const res = await fetch(`${TURSO_URL}/v2/pipeline`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${TURSO_TOKEN}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ requests, transaction_type: 'write' }),
  });
  const text = await res.text();
  if (!res.ok) throw new Error(`Turso HTTP ${res.status}: ${text}`);
  const json = JSON.parse(text);
  const err = (json.results || []).find((r) => r.type === 'err');
  if (err) throw new Error(`Turso stmt error: ${err.error}`);
  return json;
}

(async () => {
  const now = Date.now();
  const stmts = USERS.map((u) => ({
    sql: `INSERT INTO users (id, email, display_name, password_hash, role, disabled, created_at, last_login)
          VALUES (?, ?, ?, ?, ?, 0, ?, NULL)
          ON CONFLICT(email) DO UPDATE SET
            display_name=excluded.display_name,
            password_hash=excluded.password_hash,
            role=excluded.role`,
    args: [
      txt('usr_' + crypto.randomBytes(6).toString('hex')),
      txt(u.email),
      txt(u.displayName),
      txt(hashPassword(defaultPassword(u.email))),
      txt(u.role),
      intOrNull(now),
    ],
  }));
  await turso(stmts);

  const count = await fetch(`${TURSO_URL}/v2/pipeline`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${TURSO_TOKEN}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ requests: [{ type: 'execute', stmt: { sql: 'SELECT COUNT(*) AS c FROM users', want_rows: true } }] }),
  }).then((r) => r.json());
  const total = count.results?.[0]?.response?.result?.rows?.[0]?.[0]?.value;
  console.log(`seeded ${USERS.length} users (table now has ${total})`);

  // Produce the accounts document (gitignored). Plaintext lives ONLY here + in DB hash.
  const lines = [
    '# Turso Staff Accounts — Harapan Broiler',
    '',
    '> Generated by `scripts/seed-users.js`. DO NOT commit. Delete after distribution.',
    '> Every account uses a default password = `<email-local-part>123` and is expected',
    '> to change it on first login.',
    '',
    '| Role | Email | Default Password |',
    '|------|-------|------------------|',
    ...USERS.map((u) => `| ${u.role} | ${u.email} | \`${defaultPassword(u.email)}\` |`),
    '',
  ];
  fs.writeFileSync(path.join(__dirname, '..', 'TURSO_ACCOUNTS.md'), lines.join('\n'));
  console.log('wrote TURSO_ACCOUNTS.md');
})().catch((e) => { console.error('SEED FAILED:', e.message); process.exit(1); });
