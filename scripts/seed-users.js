// Seed the Turso `users` table with staff accounts migrated from Firebase.
// Firebase Auth password hashes are NOT exportable, so every account gets a
// resettable default password: `<email-local-part>123`. Users are expected to
// change it on first login (login() returns mustChangePassword when last_login
// is NULL, and we seed last_login as NULL).
//
// Hash scheme is byte-for-byte identical to src/services/authService.ts:
//   password_hash = `${salt}$${sha256hex(salt + ":" + password)}`
//
// Run: node scripts/seed-users.js
const fs = require('fs');
